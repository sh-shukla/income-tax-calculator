// Generates CHEATSHEET.md from the same engine the UI uses — the table can
// never drift from the calculator. Run: node scripts/gen-cheatsheet.js
"use strict";
const fs = require("fs");
const path = require("path");
const T = require("../assets/engine.js");

const GROSSES = [
  1000000, 1200000, 1275000, 1500000, 1800000, 2000000, 2500000, 3000000,
  4000000, 5000000, 6000000, 7500000, 10000000, 15000000, 20000000,
];

// "Typical" old-regime deductions: 80C full ₹1.5L + NPS ₹50k + 80D ₹25k.
const TYPICAL = { c80: 150000, nps: 50000, d80: 25000 };

const fmt = (n) =>
  "₹" + Math.round(n).toLocaleString("en-IN");

function row(gross) {
  const newTax = T.newRegimeTax(T.salariedTaxable(gross, "new")).total;
  const oldBare = T.oldRegimeTax(T.salariedTaxable(gross, "old", {})).total;
  const oldTypical = T.oldRegimeTax(T.salariedTaxable(gross, "old", TYPICAL)).total;
  const bestOld = Math.min(oldBare, oldTypical);
  const winner =
    newTax < bestOld ? "New" : newTax > bestOld ? "Old" : "Tie";
  const saves = Math.abs(newTax - bestOld);
  return (
    `| ${fmt(gross)} | ${fmt(newTax)} | ${fmt(gross - newTax)} | ` +
    `${fmt(oldTypical)} | ${fmt(gross - oldTypical)} | ` +
    `**${winner}** (${fmt(saves)}) |`
  );
}

const lines = [
  "# Old vs New Regime — Take-Home Cheatsheet (FY 2026-27)",
  "",
  "Salaried resident below 60. New regime: ₹75k standard deduction, nothing else.",
  "Old regime: ₹50k standard deduction **plus typical investments** — 80C full ₹1.5L, NPS (80CCD-1B) ₹50k, 80D ₹25k = ₹2.25L. No HRA/home-loan (add yours in the [calculator](https://sh-shukla.github.io/income-tax-calculator/)).",
  "Tax includes surcharge, marginal relief and 4% cess. Generated by `scripts/gen-cheatsheet.js` from the same engine as the UI.",
  "",
  "| Gross salary | New: tax | New: take-home | Old: tax (typical ded.) | Old: take-home | Winner (saves) |",
  "|---|---|---|---|---|---|",
  ...GROSSES.map(row),
  "",
  "**Rule of thumb:** with only ₹2.25L of deductions, the new regime wins at every level above. The old regime only catches up when total deductions+exemptions (HRA, home-loan interest, 80C, NPS, 80D…) are large — roughly **₹5L+ of deductions at ₹20L+ salary**. Run your real numbers in the calculator.",
  "",
  "_Not tax advice. Verify against the Income Tax Department's own calculator before filing._",
];

fs.writeFileSync(path.join(__dirname, "..", "CHEATSHEET.md"), lines.join("\n") + "\n");
console.log("CHEATSHEET.md written:", GROSSES.length, "rows");
